-- 2) Create Dhaka South and Dhaka Sub Area (idempotent).
INSERT INTO delivery_coverage_cities (name, "divisionId", enabled)
SELECT v.name,
       (SELECT id FROM delivery_coverage_divisions WHERE name = 'Dhaka'),
       true
FROM (VALUES ('Dhaka South'), ('Dhaka Sub Area')) AS v(name)
WHERE NOT EXISTS (
  SELECT 1 FROM delivery_coverage_cities c
  WHERE c.name = v.name
    AND c."divisionId" = (SELECT id FROM delivery_coverage_divisions WHERE name = 'Dhaka')
);

